def _category_card(cat) -> str:
    items = "\n".join(
        f'        <li>{o.label}'
        + (' <span class="mut">&middot; changes hosts</span>' if o.mutating else "")
        + "</li>"
        for o in cat.options
    )
    return f"""    <div class="card">
      <h2>{cat.title}</h2>
      <ul>
{items}
      </ul>
    </div>"""


def _stack_readme(catalog: Catalog, port: int) -> str:
    return f"""# Runnable Semaphore stack — {catalog.name}

Generated by `local81 ui stack-render`. This stands up a real Semaphore (MIT)
web UI in front of the `local81` CLI, so a less-technical operator drives deploys
from dropdowns instead of a terminal.

## Quick start

```bash
cp .env.example .env        # then fill the blanks from your secret references
docker compose -f docker-compose.semaphore.yml --env-file .env up -d
open launcher.html          # the friendly landing page
./import.sh                 # create the project; then import templates.json in the UI
```

Semaphore comes up on <http://localhost:{port}>. The launcher page explains the
buttons; the task templates and their dropdown surveys are in
`../semaphore/templates.json`, and each one runs `../semaphore/dispatch/<category>.sh`.

## The demo fleet (optional)

`fleet/docker-compose.fleet.yml` builds the {len(catalog.recipes)} role containers this
catalog describes, so you have something real to deploy to:

```bash
PUBKEY="$(cat ~/.ssh/id_demo.pub)" \\
  docker compose -f fleet/docker-compose.fleet.yml up -d --build
```

## Honesty notes

- No secret literals are written here — `.env` placeholders are filled from your
  secret references at runtime, keeping local81's secrets-never-at-rest posture.
- Default key custody is `local81` (Semaphore holds no target SSH creds). Using
  Semaphore's native Key Store is gated and raises compliance finding L26-UI-001.
- Mutating actions (deploy, rollback) are labelled in the launcher; they change
  target state, the rest are read-only.
"""
