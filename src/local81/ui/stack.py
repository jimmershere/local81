"""Render a *runnable* Semaphore stack + a catalog-driven fleet, from a catalog.

This is the heaviest surface: instead of only emitting config, it emits files an
operator can ``docker compose up`` to get a working Semaphore (MIT) fronting the
``local81`` CLI, backed by PostgreSQL 17 — plus a friendly static launcher page
and the 10-host demo fleet compose, both generated from the same catalog.

Still pure: it returns ``{relative_path: text}`` and writes nothing itself, and
it never bakes a secret literal — every credential is a ``${PLACEHOLDER}`` the
operator feeds from a secret reference via ``.env``.
"""

from __future__ import annotations

from ..recipes import Catalog


def render_stack(
    catalog: Catalog,
    *,
    db_password_ref: str,
    image: str = "semaphoreui/semaphore:latest",
    pg_image: str = "postgres:17",
    semaphore_port: int = 3000,
) -> dict[str, str]:
    """Return the file tree (path -> contents) for a runnable Semaphore stack."""
    files: dict[str, str] = {}
    files["docker-compose.semaphore.yml"] = _semaphore_compose(image, pg_image, semaphore_port)
    files[".env.example"] = _env_example(db_password_ref)
    files["launcher.html"] = _launcher_html(catalog, semaphore_port)
    files["import.sh"] = _import_script(catalog, semaphore_port)
    files["fleet/docker-compose.fleet.yml"] = _fleet_compose(catalog)
    files["fleet/Dockerfile.role"] = _fleet_dockerfile(catalog)
    files["README.md"] = _stack_readme(catalog, semaphore_port)
    return files


def _semaphore_compose(image: str, pg_image: str, port: int) -> str:
    return f"""# Runnable Semaphore stack — generated by `local81 ui stack-render`.
# `docker compose -f docker-compose.semaphore.yml --env-file .env up -d`
# Semaphore (MIT) fronts the local81 CLI; PostgreSQL 17 is its backing store.
# No secret literals live here — fill .env from your secret references first.
name: local81-semaphore

services:
  postgres:
    image: {pg_image}
    environment:
      POSTGRES_DB: semaphore
      POSTGRES_USER: semaphore
      POSTGRES_PASSWORD: ${{SEMAPHORE_DB_PASSWORD:?set SEMAPHORE_DB_PASSWORD in .env}}
    volumes:
      - semaphore-pg:/var/lib/postgresql/data
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U semaphore"]
      interval: 5s
      timeout: 5s
      retries: 10

  semaphore:
    image: {image}
    depends_on:
      postgres:
        condition: service_healthy
    ports:
      - "{port}:3000"
    environment:
      SEMAPHORE_DB_DIALECT: postgres
      SEMAPHORE_DB_HOST: postgres
      SEMAPHORE_DB_PORT: "5432"
      SEMAPHORE_DB: semaphore
      SEMAPHORE_DB_USER: semaphore
      SEMAPHORE_DB_PASS: ${{SEMAPHORE_DB_PASSWORD:?set SEMAPHORE_DB_PASSWORD in .env}}
      SEMAPHORE_ADMIN: ${{SEMAPHORE_ADMIN:-admin}}
      SEMAPHORE_ADMIN_NAME: ${{SEMAPHORE_ADMIN:-admin}}
      SEMAPHORE_ADMIN_EMAIL: ${{SEMAPHORE_ADMIN_EMAIL:-admin@example.com}}
      SEMAPHORE_ADMIN_PASSWORD: ${{SEMAPHORE_ADMIN_PASSWORD:?set SEMAPHORE_ADMIN_PASSWORD in .env}}
      SEMAPHORE_ACCESS_KEY_ENCRYPTION: ${{SEMAPHORE_ACCESS_KEY_ENCRYPTION:?set SEMAPHORE_ACCESS_KEY_ENCRYPTION in .env}}
    volumes:
      # Mount the control-node project so templates can shell out to `local81`.
      - ${{LOCAL81_DIR:-../..}}:/srv/local81:rw
    restart: unless-stopped

volumes:
  semaphore-pg:
"""


def _env_example(db_password_ref: str) -> str:
    return f"""# Copy to .env and fill from your secret references — NEVER commit real values.
# Source of truth for the DB password reference: {db_password_ref}
#
# Generate strong values, e.g.:
#   openssl rand -base64 32   # for SEMAPHORE_ACCESS_KEY_ENCRYPTION
SEMAPHORE_DB_PASSWORD=
SEMAPHORE_ADMIN=admin
SEMAPHORE_ADMIN_EMAIL=admin@example.com
SEMAPHORE_ADMIN_PASSWORD=
SEMAPHORE_ACCESS_KEY_ENCRYPTION=
# Absolute path to your local81 project (mounted into Semaphore as /srv/local81)
LOCAL81_DIR=../..
"""


def _import_script(catalog: Catalog, port: int) -> str:
    return f"""#!/usr/bin/env bash
# Best-effort: log into the running Semaphore and create the '{catalog.name}'
# project, then print the rendered templates to import. Semaphore's API surface
# varies by version, so this script favours clarity over cleverness: it gets you
# a session cookie and the project, then tells you exactly what to import.
set -euo pipefail
BASE="${{SEMAPHORE_URL:-http://localhost:{port}}}"
USER="${{SEMAPHORE_ADMIN:-admin}}"
PASS="${{SEMAPHORE_ADMIN_PASSWORD:?export SEMAPHORE_ADMIN_PASSWORD}}"
JAR="$(mktemp)"

echo ">> logging in to $BASE"
curl -fsS -c "$JAR" -H 'Content-Type: application/json' \\
  -d "{{\\"auth\\":\\"$USER\\",\\"password\\":\\"$PASS\\"}}" "$BASE/api/auth/login" >/dev/null

echo ">> creating project '{catalog.name}' (ignore error if it already exists)"
curl -fsS -b "$JAR" -H 'Content-Type: application/json' \\
  -d '{{"name":"{catalog.name}","alert":false}}' "$BASE/api/projects" || true

echo
echo ">> Templates to create are in ../semaphore/templates.json"
echo ">> Dispatcher scripts are in ../semaphore/dispatch/ (mounted at /srv/local81/.local81/ui/semaphore/dispatch)"
echo ">> Open $BASE and add a Bash task template per entry, pasting its survey_vars."
"""


def _fleet_dockerfile(catalog: Catalog) -> str:
    # Union of packages across recipes keeps one image that satisfies every role.
    pkgs: list[str] = []
    for r in catalog.recipes:
        for p in r.packages:
            if p not in pkgs:
                pkgs.append(p)
    pkg_line = " ".join(sorted(pkgs))
    return f"""# Catalog-driven fleet image ({catalog.name}) — one image, role at run time.
# Satisfies local81's only endpoint needs: sshd + python3 + rsync + find + sha256sum.
FROM debian:12-slim
RUN apt-get update && apt-get install -y --no-install-recommends \\
        {pkg_line} \\
    && rm -rf /var/lib/apt/lists/* \\
    && mkdir -p /var/run/sshd /srv/app /var/log/app \\
    && groupadd -f operator && useradd -m -s /bin/bash -g operator operator \\
    && mkdir -p /home/operator/.ssh && chmod 700 /home/operator/.ssh
ARG PUBKEY=""
RUN echo "$PUBKEY" > /home/operator/.ssh/authorized_keys \\
    && chmod 600 /home/operator/.ssh/authorized_keys \\
    && chown -R operator:operator /home/operator/.ssh /srv/app /var/log/app
EXPOSE 22
ENTRYPOINT ["/usr/sbin/sshd", "-D", "-e"]
"""


def _fleet_compose(catalog: Catalog) -> str:
    lines = [
        f"# {catalog.name} fleet — {len(catalog.recipes)} role containers, generated from the catalog.",
        "# Build the role image once, then each service runs it with its ROLE + port.",
        "#   PUBKEY=\"$(cat ~/.ssh/id_demo.pub)\" docker compose -f docker-compose.fleet.yml up -d --build",
        f"name: {catalog.name}-fleet",
        "",
        "networks:",
        f"  {catalog.name}net:",
        f"    name: {catalog.name}net",
        "",
        "services:",
    ]
    for r in catalog.recipes:
        block = [
            f"  {r.alias}:",
            "    build:",
            "      context: .",
            "      dockerfile: Dockerfile.role",
            "      args:",
            "        PUBKEY: ${PUBKEY:?export PUBKEY with your demo public key}",
            f"    image: {catalog.name}-role:latest",
            f"    container_name: {catalog.name}-{r.alias}",
            f"    hostname: {r.alias}",
            f"    environment: {{ ROLE: {r.role} }}",
            f"    ports: [\"127.0.0.1:{r.port}:22\"]",
            f"    networks: [{catalog.name}net]",
            "    restart: \"no\"",
            f"    # {r.title}  |  health: {r.health or 'n/a'}",
        ]
        lines.extend(block)
        lines.append("")
    return "\n".join(lines)


